def hx(h: float, s: float, l: float) -> str:
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360, l, s)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def rgb(c: str) -> tuple[float, float, float]:
    return tuple(int(c[i:i + 2], 16) / 255 for i in (1, 3, 5))  # type: ignore[return-value]


def lum(c: str) -> float:
    def ch(v: float) -> float:
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = rgb(c)
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def hue_of(c: str) -> float:
    h, _l, _s = colorsys.rgb_to_hls(*rgb(c))
    return h * 360


def palette(accent: str, tint_hue: float | None, sat: float) -> dict[str, str]:
    h = hue_of(accent) if tint_hue is None else tint_hue
    deep = hx(h, sat, 0.095)
    p = {
        "deep": deep,
        "sunken": hx(h, sat, 0.075),
        "surface": hx(h, sat * 0.9, 0.125),
        "elevated": hx(h, sat * 0.8, 0.165),
        "hover": hx(h, sat * 0.8, 0.195),
        "border": hx(h, sat * 0.7, 0.235),
        "border-hover": hx(h, sat * 0.6, 0.38),
        "text": hx(h, 0.22, 0.905),
        "text-muted": hx(h, 0.07, 0.725),
        "text-dim": hx(h, 0.06, 0.63),
        "accent": accent,
    }
    ah, al, as_ = colorsys.rgb_to_hls(*rgb(accent))
    p["accent-strong"] = hx(ah * 360, as_, min(0.85, al + 0.08))
    p["accent-dim"] = hx(ah * 360, as_ * 0.8, max(0.3, al - 0.12))
    dark_ink = hx(h, sat, 0.09)
    p["accent-ink"] = dark_ink if contrast(accent, dark_ink) >= 4.5 else "#ffffff"
    return p


