def block(sel: str, p: dict[str, str]) -> str:
    lines = [f"{sel} {{"]
    for k, v in p.items():
        lines.append(f"  --hoard-{k}: {v};")
    r, g, b = (round(x * 255) for x in rgb(p["accent"]))
    lines.append(f"  --hoard-accent-rgb: {r}, {g}, {b};")
    lines.append(f"  --hoard-accent-soft: rgba({r}, {g}, {b}, 0.14);")
    lines.append(f"  --hoard-accent-line: rgba({r}, {g}, {b}, 0.38);")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    out = [HEADER]
    w = palette(*PALETTES["writer"])
    out.append(block(":root", w))
    for app_id, spec in PALETTES.items():
        out.append(block(f'html[data-hoard-app="{app_id}"]', palette(*spec)))
    out.append(BASE)
    print("\n\n".join(out))


if __name__ == "__main__":
    main()
