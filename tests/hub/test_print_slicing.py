def test_measures_net_support_extrusion_and_separate_filament_times(tmp_path):
    path = tmp_path / "plate_1.gcode"
    path.write_text(GCODE, encoding="utf-8")
    report = print_gcode.measure(path)
    assert report["estimated_seconds"] == 141
    assert report["layers"] == 1
    assert report["filament_changes"] == 1
    assert report["support_mm3"] == 13.5
    assert [(f["colour"], f["material_g"], f["deposition_seconds"]) for f in report["filaments"]] == [
        ("#D24734", 0.03, 2.0), ("#285BD4", 0.02, 0.5),
    ]
    path.write_text(GCODE + "; total filament change = 3\n; COLOR_CHANGE,T0\n", encoding="utf-8")
    assert print_gcode.measure(path)["filament_changes"] == 4
    path.write_text("G1 X1 E3 F100\n", encoding="utf-8")
    assert print_gcode.measure(path)["support_mm3"] is None
    assert print_gcode.measure(path)["filament_changes"] is None


@pytest.mark.parametrize("exit_code", [0, 7])
def test_slice_records_defects_in_order_and_undoes_them_together(served, tmp_path, monkeypatch, exit_code):
    hub, url = served
    headers = {"Authorization": f"Bearer {hub.token}"}

    def call(name, **args):
        status, body = _http(f"{url}/api/agent/tools/{name}", args, headers)
        assert status == 200, body
        return body["result"]

    actor = {"agent": "codex-slice-test", "space_id": "ecosystem"}
    order = call("hub_agora_order_create", **actor, title="Print a test piece", words="Check a small overhang")["order"]
    jobs = call("hub_agora_plan_set", **actor, order_id=order["id"], jobs=[
        {"key": "slice", "title": "Slice", "station": "vulcan", "produces": ["gcode"]},
    ])["keys"]
    mesh = tmp_path / "source.3mf"
    with ZipFile(mesh, "w") as archive:
        archive.writestr("3D/3dmodel.model", "<model unit='millimeter'/>")
    source = call("hub_agora_piece_add", **actor, order_id=order["id"], kind="coloured-3mf", path=str(mesh),
                  title="Small 3MF")["piece"]
    mesh.write_text("the registered revision must still be used", encoding="utf-8")

    def launch(command, **options):
        assert "--debug" in command
        assert Path(command[-1]).is_file()
        with ZipFile(command[-1]) as pinned:
            assert pinned.read("3D/3dmodel.model") == b"<model unit='millimeter'/>"
        log = options["stdout"]
        log.write(b"[warning] cli mode, Current OrcaSlicer Version 2.3.1\n")
        log.write(b"[error] calc_exclude_triangles:Unable to create exclude triangles\n")
        log.write(b"[warn] Check the first layer\n[warn] Check the first layer\n")
        if not exit_code:
            out = Path(command[command.index("--outputdir") + 1])
            (out / "plate_1.gcode").write_text(GCODE, encoding="utf-8")
            (out / "result.json").write_text(json.dumps({
                "return_code": 0, "sliced_plates": [{"id": 1, "warning_message": "Additional plate warning"}],
            }), encoding="utf-8")
        return SimpleNamespace(returncode=exit_code)

    monkeypatch.setattr(local_programs, "discover", lambda *a, **kw: [{"id": "orcaslicer", "path": "test", "version": "2.3.1"}])
    monkeypatch.setattr(print_slicing.subprocess, "run", launch)
    presets = {}
    for kind in ("machine", "process", "filament"):
        path = tmp_path / f"{kind}.json"
        path.write_text(json.dumps({"type": kind, "name": f"Fixture {kind}"}), encoding="utf-8")
        presets[kind] = str(path)
    result = call("hub_print_slice", **actor, piece_id=source["id"], task_id=jobs["slice"], machine=presets["machine"],
                  process=presets["process"], filaments=[presets["filament"]], expected_filaments=2, require_support=True)
    piece = result["piece"]
    assert result["gcode_generated"] == (exit_code == 0)
    assert not result["checks_clear"]
    assert piece["kind"] == ("slice-report" if exit_code else "gcode")
    assert piece["derives_from"] == [source["id"]]
    report = piece["slice_report"]
    assert report["diagnostics"][0]["code"] == "bed_exclusion_preview"
    assert report["diagnostics"][1]["count"] == 2
    assert report["exit_code"] == exit_code
    assert piece["defects_open"] == 3
    assert {d["source"] for d in piece["defects"]} == {"check"}
    assert Path(result["receipt"]).is_file() and Path(result["log"]).is_file()

    gate = call("hub_agora_gate_open", **actor, order_id=order["id"], piece_ids=[piece["id"]], title="Slicing")
    current = call("hub_agora_order", space_id=actor["space_id"], order_id=order["id"])["order"]
    note = current["gates"][0]["technical_advisories"][0]["note"]
    assert "calc_exclude_triangles" in note
    assert ("Sin G-code" if exit_code else "Filament changes 1") in note
    status, loaded = _http(f"{url}/api/programs/print-slice-reports?piece={piece['id']}&piece={source['id']}&piece=-1", None)
    assert status == 200 and loaded["reports"] == {str(piece["id"]): report}
    assert call("hub_agora_order_undo", **actor, token=gate["undo"])["ok"]
    for token in result["undo"]:
        assert call("hub_agora_order_undo", **actor, token=token)["ok"]
    assert not call("hub_agora_job", space_id=actor["space_id"], task_id=jobs["slice"])["job"]["defects"]
